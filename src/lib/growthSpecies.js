//   만개한 채로 BLOOM_HOLD 만큼 머문 뒤 새 씨앗이 돋는다 — 만개가 «끝» 이 아니라 «한 송이 완성» 이 된다.
//   ⚠️ 저장하지 않는다. 누적 점수 하나에서 «몇 번째 꽃 · 그 안에서 몇 점» 을 나눠 쓰므로
//      DB 는 지금 그대로다(인증 기록에서 계산한 growth_points 만 있으면 된다).
export const BLOOM_HOLD = 30
export const CYCLE_PT = STAGE_PT[4] + BLOOM_HOLD      // 한 송이를 피우고 머무는 총 점수

export const cycleOf = (pt) => Math.floor(Math.max(0, pt) / CYCLE_PT)   // 0 = 첫 꽃
export const inCycleOf = (pt) => Math.max(0, pt) % CYCLE_PT             // 이번 꽃의 점수
export const stageOf = (pt) => { const v = inCycleOf(pt); let s = 0; for (let i = 1; i <= 4; i++) if (v >= STAGE_PT[i]) s = i; return s }
export const pctOf = (pt) => {
  const v = inCycleOf(pt), s = stageOf(pt)
  if (s >= 4) return 100
  const a = STAGE_PT[s], b = STAGE_PT[s + 1]
  return Math.max(0, Math.min(100, Math.round(((v - a) / (b - a)) * 100)))
}
// 다음 단계까지 남은 점수(만개면 다음 «꽃» 까지)
export const needOf = (pt) => {
  const v = inCycleOf(pt), s = stageOf(pt)
  return s >= 4 ? CYCLE_PT - v : STAGE_PT[s + 1] - v
}

// 참여자 → 꽃 종. 참여자가 고르지 않으므로 «user_id + program_id» 로 정하고, 꽃 차례마다 바꾼다.
//   ⚠️ 해시를 «차례까지 섞어» 쓰면 한 사람이 같은 종을 연달아 받을 수 있다.
//      대신 시드로 종 «순서» 를 한 번 섞어두고 차례로 고른다 —
//      첫 한 바퀴(종 수만큼)는 반드시 모두 다른 종이고, 그 뒤엔 같은 순서로 되풀이된다.
//   · 같은 프로그램·같은 차례에서는 늘 같은 종(정원이 흔들리지 않는다)
//   · 프로그램이 다르면 순서 자체가 달라진다
export const speciesFor = (uid, seed, cycle = 0) => {
  const key = String(uid) + '|' + String(seed || '')
  let h = 0
  for (let i = 0; i < key.length; i++) h = (h * 31 + key.charCodeAt(i)) >>> 0
  let r = h || 1
  const rnd = () => { r = (r * 1103515245 + 12345) >>> 0; return r / 4294967296 }
  const order = [...SPECIES_KEYS]
  for (let i = order.length - 1; i > 0; i--) {          // Fisher-Yates
    const j = Math.floor(rnd() * (i + 1))
    const t = order[i]; order[i] = order[j]; order[j] = t
  }
  return order[((cycle % order.length) + order.length) % order.length]
}
